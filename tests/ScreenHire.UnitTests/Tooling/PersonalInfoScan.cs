using System.Diagnostics;
using System.Text;
using System.Text.RegularExpressions;

namespace ScreenHire.UnitTests.Tooling;

/// <summary>
/// The mechanical half of <c>.claude/rules/no-personal-info.md</c>: home-directory paths, email addresses outside the
/// reserved domains, secrets, and the committer's own name and address, in every file git would commit. This file holds
/// no real name or address: the identity comes from <c>git config</c> at run time, and on CI, which has none, that part
/// checks nothing. A finding prints only the first characters of its match, because CI logs are public.
/// </summary>
internal static partial class PersonalInfoScan
{
    /// <summary>Paths never scanned, each for its reason.</summary>
    private static readonly Dictionary<string, string> ExemptPaths = new(StringComparer.Ordinal)
    {
        // Third-party data under its own licence (disposable-email-domains.LICENSE.txt beside it), not prose we write.
        ["src/ScreenHire.Infrastructure/Verification/Data/disposable-email-domains.txt"] = "third-party data",
        // Generated by pnpm: integrity hashes and registry URLs that look like keys and are no one's data.
        ["pnpm-lock.yaml"] = "lockfile",
    };

    /// <summary>Lockfiles by name wherever they sit, generated like <c>pnpm-lock.yaml</c>.</summary>
    private static readonly string[] ExemptFileNames = ["packages.lock.json"];

    /// <summary>
    /// Azurite's development account key. Microsoft publishes it as the only key the emulator accepts, so it is no secret.
    /// </summary>
    private const string AzuriteKey = "Eby8vdM02xNOcqFlqUwJPLlmEtlCDXJ1OUzFT50uSRZ6IFsuFq2UVErCz4I6tq/K1SZFPTOtr/KBHBeksoGMGw==";

    public sealed record Finding(string Kind, string Path, int Line, string Excerpt)
    {
        public override string ToString() => $"{Kind} {Path}:{Line} ({Excerpt}...)";
    }

    private static readonly (string Kind, Regex Pattern)[] Secrets =
    [
        ("anthropic key", AnthropicKey()),
        ("openai-style key", OpenAiKey()),
        ("aws access key", AwsKey()),
        ("github token", GitHubToken()),
        ("slack token", SlackToken()),
        ("slack token", SlackAppToken()),
        ("private key", PrivateKey()),
        ("google api key", GoogleKey()),
        ("jwt", Jwt()),
    ];

    public static bool IsExempt(string path) =>
        ExemptPaths.ContainsKey(path) || ExemptFileNames.Contains(path[(path.LastIndexOf('/') + 1)..], StringComparer.Ordinal);

    /// <summary>Every finding in one file's text. <paramref name="identity"/> holds the strings matched whole.</summary>
    public static List<Finding> Scan(string path, string text, IReadOnlyList<string> identity)
    {
        var findings = new List<Finding>();
        if (IsExempt(path))
        {
            return findings;
        }

        void Add(string kind, Match match) =>
            findings.Add(new Finding(kind, path, LineOf(text, match.Index), match.Value[..Math.Min(4, match.Value.Length)]));

        foreach (Match match in HomePath().Matches(text))
        {
            if (!match.Groups["user"].Value.Equals("dev", StringComparison.OrdinalIgnoreCase))
            {
                Add("home path", match);
            }
        }

        // A URL's user:password@host is reported once, as credentials, not again as an address.
        var credentials = UrlCredentials().Matches(text).Select(match => (match.Index, End: match.Index + match.Length)).ToList();
        foreach (Match match in Email().Matches(text))
        {
            if (!IsAllowedEmail(match.Value) && !credentials.Any(range => match.Index >= range.Index && match.Index < range.End))
            {
                Add("email", match);
            }
        }

        foreach (var (kind, pattern) in Secrets)
        {
            foreach (Match match in pattern.Matches(text))
            {
                Add(kind, match);
            }
        }

        foreach (Match match in AzureAccountKey().Matches(text))
        {
            if (match.Groups["key"].Value != AzuriteKey)
            {
                Add("azure storage key", match);
            }
        }

        foreach (Match match in ConnectionStringPassword().Matches(text))
        {
            Add("password in a connection string", match);
        }

        foreach (Match match in UrlCredentials().Matches(text))
        {
            if (!IsReservedHost(match.Groups["host"].Value))
            {
                Add("credentials in a url", match);
            }
        }

        foreach (var value in identity)
        {
            var whole = new Regex($@"(?<![\w.+-]){Regex.Escape(value)}(?![\w-])", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
            foreach (Match match in whole.Matches(text))
            {
                Add("committer identity (git config)", match);
            }
        }

        return findings;
    }

    /// <summary>
    /// The strings that name the committer: <c>user.name</c> and <c>user.email</c>, each as a whole. A value that is the
    /// repository's GitHub owner or slug (from <paramref name="originUrl"/>) is public already and left out.
    /// </summary>
    public static List<string> Identity(string? name, string? email, string? originUrl)
    {
        var allowed = originUrl is not null && GitHubRemote().Match(originUrl.Trim()) is { Success: true } remote
            ? new[] { remote.Groups["owner"].Value, $"{remote.Groups["owner"].Value}/{remote.Groups["repo"].Value}" }
            : [];
        return new[] { name, email }
            .Select(value => value?.Trim())
            .Where(value => value is { Length: >= 3 } && !allowed.Contains(value, StringComparer.OrdinalIgnoreCase))
            .Select(value => value!)
            .ToList();
    }

    /// <summary>Every file git would commit (tracked, plus untracked files no ignore rule covers), scanned.</summary>
    public static (int Files, List<Finding> Findings) ScanRepository()
    {
        var root = RepositoryFiles.PathTo();
        var identity = Identity(Git(root, "config", "--get", "user.name"), Git(root, "config", "--get", "user.email"),
            Git(root, "remote", "get-url", "origin"));
        var files = (Git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard") ?? "")
            .Split('\0', StringSplitOptions.RemoveEmptyEntries)
            .Distinct(StringComparer.Ordinal)
            .Where(file => File.Exists(Path.Combine(root, file)))
            .ToList();
        var findings = new List<Finding>();
        foreach (var file in files)
        {
            var bytes = File.ReadAllBytes(Path.Combine(root, file));
            if (bytes.AsSpan(0, Math.Min(bytes.Length, 8000)).Contains((byte)0))
            {
                continue; // binary: an image, a font, a PDF
            }

            findings.AddRange(Scan(file, Encoding.UTF8.GetString(bytes), identity));
        }

        return (files.Count, findings);
    }

    private static bool IsAllowedEmail(string address)
    {
        if (AssetName().IsMatch(address))
        {
            return true; // icon@2x.png and the like: a file name, not an address
        }

        var at = address.LastIndexOf('@');
        var local = address[..at];
        var domain = address[(at + 1)..].ToLowerInvariant();
        return IsReservedHost(domain)
            || domain == "users.noreply.github.com"
            || (local == "git" && domain == "github.com") // an SSH clone URL, git@github.com:owner/repo.git
            || (local.Equals("noreply", StringComparison.OrdinalIgnoreCase) && domain is "github.com" or "anthropic.com");
    }

    /// <summary>
    /// Domains that can never belong to anyone (RFC 2606, RFC 6761): example.com, example.org and example.net with their
    /// subdomains, the .example, .test, .invalid and .localhost names, and localhost itself.
    /// </summary>
    private static bool IsReservedHost(string host)
    {
        host = host.ToLowerInvariant().TrimEnd('.');
        return host is "localhost" or "example.com" or "example.org" or "example.net"
            || host.EndsWith(".example.com", StringComparison.Ordinal)
            || host.EndsWith(".example.org", StringComparison.Ordinal)
            || host.EndsWith(".example.net", StringComparison.Ordinal)
            || host.EndsWith(".example", StringComparison.Ordinal)
            || host.EndsWith(".test", StringComparison.Ordinal)
            || host.EndsWith(".invalid", StringComparison.Ordinal)
            || host.EndsWith(".localhost", StringComparison.Ordinal);
    }

    private static int LineOf(string text, int index) => text.AsSpan(0, index).Count('\n') + 1;

    private static string? Git(string root, params string[] arguments)
    {
        var start = new ProcessStartInfo("git", ["-C", root, "-c", "core.quotepath=false", .. arguments])
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            StandardOutputEncoding = Encoding.UTF8,
            UseShellExecute = false,
        };
        using var process = Process.Start(start) ?? throw new InvalidOperationException("Could not start git.");
        _ = process.StandardError.ReadToEndAsync();
        var output = process.StandardOutput.ReadToEnd();
        process.WaitForExit();
        // A value git has no setting for (user.email on CI) exits 1: there is nothing to match.
        return process.ExitCode == 0 ? output.TrimEnd('\n', '\r') : null;
    }

    /// <summary>
    /// A home folder on any OS, with any user but the placeholder dev: Windows' <c>Users</c> folder under a drive letter
    /// (either slash), the same folder as Git Bash (<c>/c/</c>) and WSL (<c>/mnt/c/</c>) spell it, Linux's <c>/home</c>
    /// and macOS's <c>/Users</c>.
    /// </summary>
    [GeneratedRegex(@"\b[A-Za-z]:[\\/]{1,2}Users[\\/]{1,2}(?<user>[\w.-]+)|(?<![\w.~-])(?:/mnt)?/[a-z]/Users/(?<user>[\w.-]+)|(?<![\w.~-])/(?:home|Users)/(?<user>[\w.-]+)")]
    private static partial Regex HomePath();

    [GeneratedRegex(@"(?<![\w.%+-])[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}\b")]
    private static partial Regex Email();

    [GeneratedRegex(@"\.(?:png|jpe?g|gif|svg|webp|avif|ico|js|mjs|ts|css|json|woff2?)$", RegexOptions.IgnoreCase)]
    private static partial Regex AssetName();

    [GeneratedRegex(@"sk-ant-[A-Za-z0-9_-]{20,}")]
    private static partial Regex AnthropicKey();

    [GeneratedRegex(@"\bsk-(?!ant-)[A-Za-z0-9_-]{32,}")]
    private static partial Regex OpenAiKey();

    [GeneratedRegex(@"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b")]
    private static partial Regex AwsKey();

    [GeneratedRegex(@"\b(?:gh[pousr]_[A-Za-z0-9]{36,}|github_pat_[A-Za-z0-9_]{40,})")]
    private static partial Regex GitHubToken();

    /// <summary>A Slack token as Slack issues one: its type, then a numeric id. A fixture such as xoxb-fictional is not.</summary>
    [GeneratedRegex(@"\bxox[abprs]-\d{6,}-[A-Za-z0-9-]{10,}")]
    private static partial Regex SlackToken();

    /// <summary>A Slack app-level token (<c>xapp-</c>) or a refresh token (<c>xoxe-</c>, <c>xoxe.xoxp-</c>).</summary>
    [GeneratedRegex(@"\b(?:xapp|xoxe(?:\.xox[bp])?)-\d-[A-Za-z0-9-]{20,}")]
    private static partial Regex SlackAppToken();

    [GeneratedRegex(@"-----BEGIN [A-Z ]*PRIVATE KEY-----")]
    private static partial Regex PrivateKey();

    [GeneratedRegex(@"\bAIza[0-9A-Za-z_-]{35}\b")]
    private static partial Regex GoogleKey();

    [GeneratedRegex(@"\beyJ[A-Za-z0-9_-]{15,}\.eyJ[A-Za-z0-9_-]{15,}\.[A-Za-z0-9_-]{10,}")]
    private static partial Regex Jwt();

    [GeneratedRegex(@"AccountKey=(?<key>[A-Za-z0-9+/=]{40,})")]
    private static partial Regex AzureAccountKey();

    /// <summary>A password value in a connection string; a placeholder (<c>$</c>, <c>{</c>, <c>&lt;</c>, <c>%</c>) is not one.</summary>
    [GeneratedRegex(@"\b(?:Password|Pwd)=(?![$\{<%;])[^;""'\s`]{4,}", RegexOptions.IgnoreCase)]
    private static partial Regex ConnectionStringPassword();

    [GeneratedRegex(@"\b[a-z][a-z0-9+.-]*://[^\s:/@""'`]+:[^\s@/""'`{$<]{3,}@(?<host>[A-Za-z0-9.-]+)", RegexOptions.IgnoreCase)]
    private static partial Regex UrlCredentials();

    [GeneratedRegex(@"github\.com[:/](?<owner>[^/\s]+)/(?<repo>[^/\s]+?)(?:\.git)?/?$", RegexOptions.IgnoreCase)]
    private static partial Regex GitHubRemote();
}
